/// Shortcut for grabbing the typed admin API off the per-request context.
fn admin<P>(ctx: &PluginContext<AdminState<P>, P>) -> &PlatformAdminApi {
    &ctx.resources.platform_admin
}

fn parse_uuid(value: &str, field: &str) -> Result<Uuid, ConnectError> {
    Uuid::parse_str(value).map_err(|_| invalid_field(field))
}

fn require_nonempty(value: &str, field: &str) -> Result<String, ConnectError> {
    if value.trim().is_empty() {
        Err(required_field(field))
    } else {
        Ok(value.to_string())
    }
}

fn optional(value: &str) -> Option<String> {
    if value.is_empty() {
        None
    } else {
        Some(value.to_string())
    }
}

/// Empty proto string → `None`; anything else → `Some(&str)`. Used for
/// partial-update RPCs that pass-through unchanged fields.
fn non_empty_str(value: &str) -> Option<&str> {
    if value.is_empty() { None } else { Some(value) }
}

fn invalid_field(field: &str) -> ConnectError {
    ConnectError::invalid_argument(format!("admin.error.field_invalid:{field}"))
}

fn required_field(field: &str) -> ConnectError {
    ConnectError::invalid_argument(format!("admin.error.field_required:{field}"))
}
