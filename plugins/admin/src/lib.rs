//! `admin` plugin (M18 Stage 2). Provides the platform's management surface:
//! groups, group-roles, group memberships, user-roles, user-role assignments,
//! and a read-only permission catalogue.
//!
//! Every mutation goes through `ctx.resources.platform_admin` — the typed
//! [`junius_sdk::PlatformAdminApi`] accessor — which runs on the platform
//! pool (plugins have no SELECT/INSERT on `platform.group*`/`user_role*`) and
//! audit-emits every change. The accessor is itself gated on the
//! `platform.admin` capability declared in this plugin's `plugin.toml`; the
//! host's trusted-capability allowlist additionally refuses to boot if any
//! other plugin declares the capability.
//!
//! Static RPC permission gating is via each method's
//! `option (platform.v1.requires)` annotation in `proto/admin/v1/admin.proto`.
//! The built-in `admin` user-role's wildcard (`*`) passes every gate
//! transparently; admins do not need explicit `admin:groups.read` etc. grants.

