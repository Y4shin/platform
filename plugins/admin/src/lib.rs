struct UserAdminRpc;

#[junius_sdk::rpc_service(UserAdminService)]
impl UserAdminRpc {
    async fn find_user_by_email(
        &self,
        actx: AdminCtx<crate::__rpc_requires::user_admin_service::FindUserByEmail>,
        request: OwnedFindUserByEmailRequestView,
    ) -> ServiceResult<impl Encodable<pb::FindUserByEmailResponse>> {
        let email = require_nonempty(request.email, "email")?;
        let id = admin(&actx).find_user_by_email(&email).await?;
        let (user_id, display_name) = match id {
            Some(uid) => {
                // The admin API's display-name lookup goes through the public
                // users handle so we get the email-display pair in one shot.
                let display = actx
                    .resources
                    .users
                    .lookup(uid)
                    .await?
                    .map(|u| u.display_name)
                    .unwrap_or_default();
                (uid.to_string(), display)
            }
            None => (String::new(), String::new()),
        };
        Ok(Response::new(pb::FindUserByEmailResponse {
            user_id,
            display_name,
            ..Default::default()
        }))
    }
}

