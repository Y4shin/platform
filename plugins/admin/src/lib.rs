/// Per-request state for the admin plugin. The plugin holds no typed repos —
/// every mutation flows through `PluginResources::platform_admin` — so the
/// struct is empty save for the permission-witness phantom. `#[derive(PluginCtx)]`
/// only accepts `#[repo]` fields, so we hand-implement [`Clone`] +
/// [`BuildState`] here; the `AdminCtx<P>` alias gives handlers the same
/// extractor ergonomics as the macro-generated form.
pub struct AdminState<P = ()> {
    _phantom: std::marker::PhantomData<P>,
}

impl<P> Clone for AdminState<P> {
    fn clone(&self) -> Self {
        Self {
            _phantom: std::marker::PhantomData,
        }
    }
}

impl<P> BuildState for AdminState<P> {
    fn build(_resources: &PluginResources, _user: Option<&User>) -> Self {
        Self {
            _phantom: std::marker::PhantomData,
        }
    }
}

pub type AdminCtx<P> = PluginContext<AdminState<P>, P>;

pub struct AdminPlugin;

impl AdminPlugin {
    #[must_use]
    pub fn new() -> Self {
        Self
    }
}

impl Default for AdminPlugin {
    fn default() -> Self {
        Self::new()
    }
}

#[async_trait]
impl Plugin for AdminPlugin {
    fn metadata(&self) -> &'static PluginMetadata {
        &METADATA
    }

    fn routes(&self) -> Router {
        Router::new().route("/ping", get(|| async { "pong" }))
    }

    fn register_rpc(&self, router: connectrpc::Router) -> connectrpc::Router {
        let router = Arc::new(GroupAdminRpc).register(router);
        let router = Arc::new(UserRoleAdminRpc).register(router);
        let router = Arc::new(UserAdminRpc).register(router);
        let router = Arc::new(OidcMappingAdminRpc).register(router);
        let router = Arc::new(PermissionCatalogRpc).register(router);
        Arc::new(AuditRpc).register(router)
    }
}

