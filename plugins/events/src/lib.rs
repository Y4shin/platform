/// Connect-RPC implementation of `events.v1.EventService`. The `#[rpc_service]`
/// macro rewrites each handler into the shape the `connectrpc` trait expects:
/// the ctx parameter's witness alias resolves to the proto method's
/// `(platform.v1.requires)` set, the macro prepends the `from_rpc` resolution,
/// and the host's RPC guard enforces the same set pre-dispatch.
struct EventRpc;

#[junius_sdk::rpc_service(EventService)]
impl EventRpc {
    async fn list_events(
        &self,
        ectx: EventCtx<crate::__rpc_requires::event_service::ListEvents>,
        _request: OwnedListEventsRequestView,
    ) -> ServiceResult<impl Encodable<pb::ListEventsResponse>> {
        let events = ectx.state.events.list().await?;
        Ok(Response::new(pb::ListEventsResponse {
            events: events.into_iter().map(event_to_proto).collect(),
            ..Default::default()
        }))
    }

    async fn get_event(
        &self,
        ectx: EventCtx<crate::__rpc_requires::event_service::GetEvent>,
        request: OwnedGetEventRequestView,
    ) -> ServiceResult<impl Encodable<pb::GetEventResponse>> {
        let id = EventId(parse_uuid(request.id, "id")?);
        let event = ectx.state.events.get(id).await?;
        Ok(Response::new(pb::GetEventResponse {
            event: Some(event_to_proto(event)).into(),
            ..Default::default()
        }))
    }

    async fn create_event(
        &self,
        ectx: EventCtx<crate::__rpc_requires::event_service::CreateEvent>,
        request: OwnedCreateEventRequestView,
    ) -> ServiceResult<impl Encodable<pb::CreateEventResponse>> {
        let caller = ectx
            .user
            .as_ref()
            .map(|u| u.id)
            .ok_or_else(|| ConnectError::unauthenticated("events.error.auth_required"))?;
        // Resolve + authorize the owner: a user event is owned by the caller; a
        // group event requires the caller to belong to that group.
        let owner = match request.owner_kind {
            "user" | "" => Principal::User(caller),
            "group" => {
                let gid = GroupId(parse_uuid(request.owner_id, "owner_id")?);
                if !ectx.resources.groups.is_member(gid, caller).await? {
                    return Err(err::group_membership_required());
                }
                Principal::Group(gid)
            }
            _ => {
                return Err(err::invalid_owner_kind());
            }
        };
        let new = NewEvent {
            title: require_nonempty(request.title, "title")?,
            description: optional(request.description),
            location: optional(request.location),
            starts_at: parse_rfc3339(request.starts_at, "starts_at")?,
            ends_at: parse_optional_rfc3339(request.ends_at)?,
            all_day: request.all_day,
            visibility: parse_visibility(request.visibility)?,
        };
        let created = ectx
            .state
            .events
            .create(new, owner, &ectx.resources.authz)
            .await?;
        Ok(Response::new(pb::CreateEventResponse {
            event: Some(event_to_proto(created)).into(),
            ..Default::default()
        }))
    }

    async fn update_event(
        &self,
        ectx: EventCtx<crate::__rpc_requires::event_service::UpdateEvent>,
        request: OwnedUpdateEventRequestView,
    ) -> ServiceResult<impl Encodable<pb::UpdateEventResponse>> {
        let id = EventId(parse_uuid(request.id, "id")?);
        let update = EventUpdate {
            title: require_nonempty(request.title, "title")?,
            description: optional(request.description),
            location: optional(request.location),
            starts_at: parse_rfc3339(request.starts_at, "starts_at")?,
            ends_at: parse_optional_rfc3339(request.ends_at)?,
            all_day: request.all_day,
            visibility: parse_visibility(request.visibility)?,
        };
        let updated = ectx.state.events.update(id, update).await?;
        Ok(Response::new(pb::UpdateEventResponse {
            event: Some(event_to_proto(updated)).into(),
            ..Default::default()
        }))
    }

    async fn delete_event(
        &self,
        ectx: EventCtx<crate::__rpc_requires::event_service::DeleteEvent>,
        request: OwnedDeleteEventRequestView,
    ) -> ServiceResult<impl Encodable<pb::DeleteEventResponse>> {
        let id = EventId(parse_uuid(request.id, "id")?);
        ectx.state.events.delete(id).await?;
        Ok(Response::new(pb::DeleteEventResponse::default()))
    }

    async fn share_event(
        &self,
        ectx: EventCtx<crate::__rpc_requires::event_service::ShareEvent>,
        request: OwnedShareEventRequestView,
    ) -> ServiceResult<impl Encodable<pb::ShareEventResponse>> {
        let event_id = parse_uuid(request.id, "id")?;
        let principal = parse_principal(request.principal_kind, request.principal_id)?;
        let share = ectx
            .resources
            .authz
            .share(
                "events:event",
                event_id,
                principal,
                request.permission,
                None,
            )
            .await?;
        Ok(Response::new(pb::ShareEventResponse {
            share_id: share.id.to_string(),
            ..Default::default()
        }))
    }
}

/// Convert an event view (with the viewer's server-computed flags) into proto.
fn event_to_proto(e: EventView) -> pb::Event {
    let (owner_kind, owner_id) = match e.owner_kind {
        OwnerKind::User => ("user", e.owning_user_id),
        OwnerKind::Group => ("group", e.owning_group_id),
    };
    let visibility = match e.visibility {
        Visibility::Private => "private",
        Visibility::Public => "public",
    };
    pb::Event {
        id: e.id.to_string(),
        title: e.title,
        description: e.description.unwrap_or_default(),
        location: e.location.unwrap_or_default(),
        starts_at: e.starts_at.to_rfc3339(),
        ends_at: e.ends_at.map(|t| t.to_rfc3339()).unwrap_or_default(),
        all_day: e.all_day,
        visibility: visibility.to_string(),
        owner_kind: owner_kind.to_string(),
        owner_id: owner_id.map(|u| u.to_string()).unwrap_or_default(),
        viewer_can_edit: e.viewer_can_edit,
        viewer_can_share: e.viewer_can_share,
        ..Default::default()
    }
}

/// Parse a UUID request field, mapping a parse failure to `invalid_argument`.
fn parse_uuid(value: &str, field: &str) -> Result<Uuid, ConnectError> {
    Uuid::parse_str(value).map_err(|_| err::invalid_field(field))
}

/// An empty proto string field becomes `None`; anything else `Some`.
fn optional(value: &str) -> Option<String> {
    if value.is_empty() {
        None
    } else {
        Some(value.to_string())
    }
}

/// Require a non-empty (after trim) string field.
fn require_nonempty(value: &str, field: &str) -> Result<String, ConnectError> {
    if value.trim().is_empty() {
        Err(err::required_field(field))
    } else {
        Ok(value.to_string())
    }
}

/// Parse an RFC 3339 timestamp request field.
fn parse_rfc3339(value: &str, field: &str) -> Result<DateTime<Utc>, ConnectError> {
    DateTime::parse_from_rfc3339(value)
        .map(|d| d.with_timezone(&Utc))
        .map_err(|_| err::invalid_rfc3339(field))
}

/// Parse an optional RFC 3339 timestamp: empty → `None`.
fn parse_optional_rfc3339(value: &str) -> Result<Option<DateTime<Utc>>, ConnectError> {
    if value.is_empty() {
        Ok(None)
    } else {
        Ok(Some(parse_rfc3339(value, "ends_at")?))
    }
}

/// Parse a visibility request field; empty defaults to `private`.
fn parse_visibility(value: &str) -> Result<Visibility, ConnectError> {
    match value {
        "public" => Ok(Visibility::Public),
        "private" | "" => Ok(Visibility::Private),
        _ => Err(err::invalid_visibility()),
    }
}

/// Parse a `(principal_kind, principal_id)` pair from a `ShareEvent` request.
fn parse_principal(kind: &str, id: &str) -> Result<Principal, ConnectError> {
    match kind {
        "user" => Ok(Principal::User(UserId(parse_uuid(id, "principal_id")?))),
        "group" => Ok(Principal::Group(GroupId(parse_uuid(id, "principal_id")?))),
        "public" => Ok(Principal::Public),
        _ => Err(err::invalid_principal_kind()),
    }
}

/// Connect-RPC implementation of `events.v1.InviteService`. Owner-side methods
/// resolve to a permission-gated `EventCtx<P>` from their proto-derived alias;
/// the viewer-side methods (`GetInvite`/`Signup`/`OptOut`) carry no annotation,
/// so their alias is `()` and anonymous callers reach them — the repository's
/// runtime ACL gates the data.
struct InviteRpc;

#[junius_sdk::rpc_service(InviteService)]
impl InviteRpc {
    async fn create_invite(
        &self,
        ectx: EventCtx<crate::__rpc_requires::invite_service::CreateInvite>,
        request: OwnedCreateInviteRequestView,
    ) -> ServiceResult<impl Encodable<pb::CreateInviteResponse>> {
        let event_id = parse_uuid(request.event_id, "event_id")?;
        let caller = ectx
            .user
            .as_ref()
            .map(|u| u.id)
            .ok_or_else(|| ConnectError::unauthenticated("events.error.auth_required"))?;
        // Fetch the event (also confirms read access + gives the owner) before
        // creating its invite.
        let event = ectx.state.events.get(EventId(event_id)).await?;
        let config = InviteConfig {
            signup_enabled: request.signup_enabled,
            signup_open: request.signup_open,
            slot_limit: (request.slot_limit > 0).then_some(request.slot_limit),
            show_title: request.show_title,
            show_datetime: request.show_datetime,
            show_location: request.show_location,
            show_description: request.show_description,
            show_remaining: request.show_remaining,
        };
        let slug = crate::domain::generate_slug();
        let invite = match ectx.state.invites.create(event_id, &slug, &config).await {
            Ok(invite) => invite,
            Err(junius_sdk::RepoError::Db(e)) if is_unique_violation(&e) => {
                return Err(err::invite_already_exists());
            }
            Err(e) => return Err(e.into()),
        };
        // Group pre-sign-up: snapshot the owning group's current members as going.
        if request.presignup_group && matches!(event.owner_kind, OwnerKind::Group) {
            if let Some(gid) = event.owning_group_id {
                let members = ectx.resources.groups.members(GroupId(gid), caller).await?;
                let ids: Vec<UserId> = members.into_iter().map(|m| m.user.id).collect();
                ectx.state.signups.presign_users(invite.id, &ids).await?;
            }
        }
        Ok(Response::new(pb::CreateInviteResponse {
            invite: Some(invite_to_proto(invite)).into(),
            ..Default::default()
        }))
    }

    async fn update_invite(
        &self,
        ectx: EventCtx<crate::__rpc_requires::invite_service::UpdateInvite>,
        request: OwnedUpdateInviteRequestView,
    ) -> ServiceResult<impl Encodable<pb::UpdateInviteResponse>> {
        let event_id = parse_uuid(request.event_id, "event_id")?;
        let config = InviteConfig {
            signup_enabled: request.signup_enabled,
            signup_open: request.signup_open,
            slot_limit: (request.slot_limit > 0).then_some(request.slot_limit),
            show_title: request.show_title,
            show_datetime: request.show_datetime,
            show_location: request.show_location,
            show_description: request.show_description,
            show_remaining: request.show_remaining,
        };
        let invite = ectx.state.invites.update(event_id, &config).await?;
        Ok(Response::new(pb::UpdateInviteResponse {
            invite: Some(invite_to_proto(invite)).into(),
            ..Default::default()
        }))
    }

    async fn list_signups(
        &self,
        ectx: EventCtx<crate::__rpc_requires::invite_service::ListSignups>,
        request: OwnedListSignupsRequestView,
    ) -> ServiceResult<impl Encodable<pb::ListSignupsResponse>> {
        let event_id = parse_uuid(request.event_id, "event_id")?;
        let rows = ectx.state.invites.list_signups(event_id).await?;
        let mut signups = Vec::with_capacity(rows.len());
        for row in rows {
            // Resolve a display name/email for user sign-ups via the directory;
            // guests carry their own.
            let (display_name, email) = match row.user_id {
                Some(uid) => ectx
                    .resources
                    .users
                    .lookup(UserId(uid))
                    .await?
                    .map(|u| (u.display_name, u.email))
                    .unwrap_or_default(),
                None => (
                    row.guest_name.clone().unwrap_or_default(),
                    row.guest_email.clone().unwrap_or_default(),
                ),
            };
            signups.push(signup_to_proto(&row, display_name, email));
        }
        Ok(Response::new(pb::ListSignupsResponse {
            signups,
            ..Default::default()
        }))
    }

    async fn get_event_invite(
        &self,
        ectx: EventCtx<crate::__rpc_requires::invite_service::GetEventInvite>,
        request: OwnedGetEventInviteRequestView,
    ) -> ServiceResult<impl Encodable<pb::GetEventInviteResponse>> {
        let event_id = parse_uuid(request.event_id, "event_id")?;
        let invite = ectx.state.invites.get_for_event(event_id).await?;
        Ok(Response::new(pb::GetEventInviteResponse {
            has_invite: invite.is_some(),
            invite: invite.map(invite_to_proto).into(),
            ..Default::default()
        }))
    }

    async fn get_invite(
        &self,
        // No witness — `GetInvite` carries no `(platform.v1.requires)`, so the
        // alias resolves to `()`. Anonymous callers reach this; the repo gates.
        ectx: EventCtx<crate::__rpc_requires::invite_service::GetInvite>,
        request: OwnedGetInviteRequestView,
    ) -> ServiceResult<impl Encodable<pb::GetInviteResponse>> {
        let page = ectx.state.invites.get_page_by_slug(request.slug).await?;
        Ok(Response::new(invite_page_to_proto(page)))
    }

    async fn signup(
        &self,
        ectx: EventCtx<crate::__rpc_requires::invite_service::Signup>,
        request: OwnedSignupRequestView,
    ) -> ServiceResult<impl Encodable<pb::SignupResponse>> {
        let outcome = ectx
            .state
            .signups
            .signup(
                request.slug,
                nonempty(request.guest_name),
                nonempty(request.guest_email),
            )
            .await?;
        // Recipient: a logged-in caller uses their directory identity; a guest the
        // submitted fields. Enqueue the confirmation best-effort — a missing job
        // backend must not fail the sign-up.
        let (recipient_email, recipient_name, recipient_locale) = match ectx.user.as_ref() {
            Some(u) => (u.email.clone(), u.display_name.clone(), u.locale.clone()),
            None => (
                request.guest_email.to_string(),
                request.guest_name.to_string(),
                None,
            ),
        };
        if !recipient_email.is_empty() {
            let job = SendSignupConfirmation {
                signup_id: outcome.id.to_string(),
                event_title: outcome.event_title.clone(),
                recipient_email,
                recipient_name,
                recipient_locale,
            };
            if let Err(e) = ectx.resources.jobs.enqueue(job).await {
                tracing::warn!(error = %e, "failed to enqueue events.send_signup_confirmation");
            }
        }
        Ok(Response::new(pb::SignupResponse {
            signup_id: outcome.id.to_string(),
            status: outcome.status.as_str().to_string(),
            ..Default::default()
        }))
    }

    async fn opt_out(
        &self,
        ectx: EventCtx<crate::__rpc_requires::invite_service::OptOut>,
        request: OwnedOptOutRequestView,
    ) -> ServiceResult<impl Encodable<pb::OptOutResponse>> {
        ectx.state.signups.opt_out(request.slug).await?;
        Ok(Response::new(pb::OptOutResponse::default()))
    }
}

