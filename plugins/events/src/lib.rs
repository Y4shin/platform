/// Project the public invite page to proto, applying the `show_*` toggles so
/// hidden fields never leave the server, and computing the slot affordances.
fn invite_page_to_proto(p: InvitePage) -> pb::GetInviteResponse {
    let unlimited = p.slot_limit.is_none();
    let remaining = p.slot_limit.map_or(0, |limit| {
        let used = i32::try_from(p.going_count).unwrap_or(i32::MAX);
        limit.saturating_sub(used).max(0)
    });
    let can_signup = p.signup_enabled && p.signup_open && (unlimited || remaining > 0);
    pb::GetInviteResponse {
        slug: p.slug,
        event_id: p.event_id.to_string(),
        signup_enabled: p.signup_enabled,
        signup_open: p.signup_open,
        can_signup,
        show_remaining: p.show_remaining,
        unlimited_slots: unlimited,
        slots_remaining: if p.show_remaining && !unlimited {
            remaining
        } else {
            0
        },
        title: toggled(p.show_title, p.title),
        description: toggled(p.show_description, p.description.unwrap_or_default()),
        location: toggled(p.show_location, p.location.unwrap_or_default()),
        starts_at: toggled(p.show_datetime, p.starts_at.to_rfc3339()),
        ends_at: toggled(
            p.show_datetime,
            p.ends_at.map(|t| t.to_rfc3339()).unwrap_or_default(),
        ),
        all_day: p.show_datetime && p.all_day,
        ..Default::default()
    }
}

/// Return `value` only when `shown`, else the empty string (hidden field).
fn toggled(shown: bool, value: String) -> String {
    if shown { value } else { String::new() }
}

/// A non-empty trimmed view of a proto string field, else `None`.
fn nonempty(value: &str) -> Option<&str> {
    let trimmed = value.trim();
    (!trimmed.is_empty()).then_some(trimmed)
}

/// Whether a sqlx error is a unique-constraint violation.
fn is_unique_violation(e: &sqlx::Error) -> bool {
    e.as_database_error()
        .is_some_and(sqlx::error::DatabaseError::is_unique_violation)
}

/// Connect-RPC implementation of `events.v1.CalendarService`. Mints / lists /
/// revokes feed tokens and toggles a group's public calendar; the `.ics` feeds
/// these point at are served unauthenticated by [`crate::http`]. Group actions
/// additionally require the caller to hold `events:write` *within* the group.
struct CalendarRpc;

#[junius_sdk::rpc_service(CalendarService)]
impl CalendarRpc {
    async fn get_personal_feed(
        &self,
        ectx: EventCtx<crate::__rpc_requires::calendar_service::GetPersonalFeed>,
        _request: OwnedGetPersonalFeedRequestView,
    ) -> ServiceResult<impl Encodable<pb::GetPersonalFeedResponse>> {
        let caller = require_caller(ectx.user.as_ref())?;
        // Keys are stored hashed (not recoverable), so each call mints a fresh
        // personal key; old ones remain valid until revoked.
        let key = generate_feed_key();
        ectx.state
            .calendar
            .mint_token(
                FeedKind::Personal,
                Some(caller.0),
                None,
                caller.0,
                None,
                &hash_token(&key),
            )
            .await?;
        Ok(Response::new(pb::GetPersonalFeedResponse {
            url: format!("/h/events/ics/u/{key}"),
            ..Default::default()
        }))
    }

    async fn create_group_key(
        &self,
        ectx: EventCtx<crate::__rpc_requires::calendar_service::CreateGroupKey>,
        request: OwnedCreateGroupKeyRequestView,
    ) -> ServiceResult<impl Encodable<pb::CreateGroupKeyResponse>> {
        let group_id = parse_uuid(request.group_id, "group_id")?;
        let caller = require_user(ectx.user.as_ref())?;
        if !caller.has_permission_in_group(GroupId(group_id), "events:write") {
            return Err(err::group_write_required());
        }
        let key = generate_feed_key();
        ectx.state
            .calendar
            .mint_token(
                FeedKind::Group,
                None,
                Some(group_id),
                caller.id.0,
                nonempty(request.label),
                &hash_token(&key),
            )
            .await?;
        let name = ectx
            .resources
            .groups
            .by_id(GroupId(group_id))
            .await?
            .map_or_else(|| group_id.to_string(), |g| encode_segment(&g.name));
        Ok(Response::new(pb::CreateGroupKeyResponse {
            url: format!("/h/events/ics/g/{name}/{key}"),
            ..Default::default()
        }))
    }

    async fn set_group_public(
        &self,
        ectx: EventCtx<crate::__rpc_requires::calendar_service::SetGroupPublic>,
        request: OwnedSetGroupPublicRequestView,
    ) -> ServiceResult<impl Encodable<pb::SetGroupPublicResponse>> {
        let group_id = parse_uuid(request.group_id, "group_id")?;
        let caller = require_user(ectx.user.as_ref())?;
        if !caller.has_permission_in_group(GroupId(group_id), "events:write") {
            return Err(err::group_write_required());
        }
        ectx.state
            .calendar
            .set_group_public(group_id, request.public, caller.id.0)
            .await?;
        Ok(Response::new(pb::SetGroupPublicResponse::default()))
    }

    async fn list_feeds(
        &self,
        ectx: EventCtx<crate::__rpc_requires::calendar_service::ListFeeds>,
        _request: OwnedListFeedsRequestView,
    ) -> ServiceResult<impl Encodable<pb::ListFeedsResponse>> {
        let caller = require_caller(ectx.user.as_ref())?;
        let tokens = ectx.state.calendar.list_tokens(caller.0).await?;
        Ok(Response::new(pb::ListFeedsResponse {
            feeds: tokens.into_iter().map(feed_to_proto).collect(),
            ..Default::default()
        }))
    }

    async fn revoke_feed(
        &self,
        ectx: EventCtx<crate::__rpc_requires::calendar_service::RevokeFeed>,
        request: OwnedRevokeFeedRequestView,
    ) -> ServiceResult<impl Encodable<pb::RevokeFeedResponse>> {
        let token_id = parse_uuid(request.id, "id")?;
        let caller = require_caller(ectx.user.as_ref())?;
        ectx.state.calendar.revoke_token(token_id, caller.0).await?;
        Ok(Response::new(pb::RevokeFeedResponse::default()))
    }
}

/// The authenticated caller's id, or `unauthenticated` (gated methods should
/// always have one, but be defensive).
fn require_caller(user: Option<&User>) -> Result<UserId, ConnectError> {
    Ok(require_user(user)?.id)
}

/// The authenticated caller, or `unauthenticated`.
fn require_user(user: Option<&User>) -> Result<&User, ConnectError> {
    user.ok_or_else(|| ConnectError::unauthenticated("events.error.auth_required"))
}

/// Error-code helpers. Backend handlers emit stable `events.error.<code>` IDs
/// (with optional positional args separated by `:`) as `ConnectError` messages;
/// the frontend's `eventsError(err, t)` mapper renders the matching translated
/// string via Lingui. Keeps RPC errors out of the UI's English-only path.
mod err {
    use connectrpc::ConnectError;
    pub fn invalid_field(field: &str) -> ConnectError {
        ConnectError::invalid_argument(format!("events.error.field_invalid:{field}"))
    }
    pub fn required_field(field: &str) -> ConnectError {
        ConnectError::invalid_argument(format!("events.error.field_required:{field}"))
    }
    pub fn invalid_rfc3339(field: &str) -> ConnectError {
        ConnectError::invalid_argument(format!("events.error.field_invalid_rfc3339:{field}"))
    }
    pub fn invalid_visibility() -> ConnectError {
        ConnectError::invalid_argument("events.error.field_invalid_visibility")
    }
    pub fn invalid_owner_kind() -> ConnectError {
        ConnectError::invalid_argument("events.error.field_invalid_owner_kind")
    }
    pub fn invalid_principal_kind() -> ConnectError {
        ConnectError::invalid_argument("events.error.field_invalid_principal_kind")
    }
    pub fn group_membership_required() -> ConnectError {
        ConnectError::permission_denied("events.error.group_membership_required")
    }
    pub fn group_write_required() -> ConnectError {
        ConnectError::permission_denied("events.error.group_write_required")
    }
    pub fn invite_already_exists() -> ConnectError {
        ConnectError::already_exists("events.error.invite_already_exists")
    }
}

/// Convert a feed token into proto.
fn feed_to_proto(t: TokenInfo) -> pb::Feed {
    pb::Feed {
        id: t.id.to_string(),
        kind: match t.kind {
            FeedKind::Personal => "personal",
            FeedKind::Group => "group",
        }
        .to_string(),
        group_id: t
            .subject_group_id
            .map(|g| g.to_string())
            .unwrap_or_default(),
        label: t.label.unwrap_or_default(),
        created_at: t.created_at.to_rfc3339(),
        revoked: t.revoked,
        ..Default::default()
    }
}

/// Percent-encode a single URL path segment (group name in a feed URL is
/// cosmetic — the key is the credential — but the URL must still be valid).
fn encode_segment(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for byte in s.bytes() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(byte as char);
            }
            other => {
                use std::fmt::Write;
                let _ = write!(out, "%{other:02X}");
            }
        }
    }
    out
}

/// Background job (M10): email a sign-up confirmation. Enqueued by the `Signup`
/// handler; run out-of-band by the host job worker, which sends it via the gated
/// `email.send` capability.
/// `recipient_locale` is captured at enqueue time (M14); the worker uses it
/// to render the subject and body in the recipient's locale even though the
/// job runs out-of-band without an HTTP request.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SendSignupConfirmation {
    pub signup_id: String,
    pub event_title: String,
    pub recipient_email: String,
    pub recipient_name: String,
    /// Recipient's locale code (e.g. `"en"`, `"de"`). `None` falls back to the
    /// deployment default.
    #[serde(default)]
    pub recipient_locale: Option<String>,
}

impl Job for SendSignupConfirmation {
    const NAME: &'static str = "events.send_signup_confirmation";
}

/// Handler for [`SendSignupConfirmation`] — runs in the worker with the plugin's
/// own resources, emailing the attendee via the gated `email.send` capability.
async fn send_signup_confirmation_handler(
    job: SendSignupConfirmation,
    resources: PluginResources,
) -> Result<(), PluginError> {
    let l = resources
        .localizer
        .for_stored(job.recipient_locale.as_deref());
    let trimmed = job.recipient_name.trim();
    // Guests with an empty `recipient_name` get a locale-specific fallback
    // ("there" in EN, "zusammen" in DE).
    let fallback = l.t(messages::EventsSignupEmailRecipientFallback);
    let name = if trimmed.is_empty() {
        &fallback
    } else {
        trimmed
    };
    resources
        .email
        .send(EmailMessage {
            to: vec![job.recipient_email],
            subject: l.t(messages::EventsSignupEmailSubject {
                title: &job.event_title,
            }),
            body_text: l.t(messages::EventsSignupEmailBody {
                name,
                title: &job.event_title,
            }),
            ..Default::default()
        })
        .await
}

