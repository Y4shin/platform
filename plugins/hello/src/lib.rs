/// Background job (M10): email a greeting after it's created. Enqueued by
/// `create_greeting`; handled out-of-band by the host job worker.
///
/// `recipient_locale` is captured at enqueue time (M14); the worker uses it
/// to render the subject/body in the recipient's locale even though the job
/// runs out-of-band without an HTTP request.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SendGreeting {
    pub greeting_id: String,
    pub name: String,
    pub body: String,
    pub recipient_email: String,
    /// Recipient's locale code (e.g. `"en"`, `"de"`). `None` falls back to the
    /// deployment default.
    #[serde(default)]
    pub recipient_locale: Option<String>,
}

impl Job for SendGreeting {
    const NAME: &'static str = "hello.send_greeting";
}

/// Handler for [`SendGreeting`] — runs in the worker with the plugin's own
/// resources, sending the greeting via the gated `email.send` capability.
async fn send_greeting_handler(
    job: SendGreeting,
    resources: PluginResources,
) -> Result<(), PluginError> {
    let subject = resources
        .localizer
        .for_stored(job.recipient_locale.as_deref())
        .t(messages::HelloEmailSubject { name: &job.name });
    resources
        .email
        .send(EmailMessage {
            to: vec![job.recipient_email],
            subject,
            body_text: job.body,
            ..Default::default()
        })
        .await
}

/// Convert a stored greeting into its proto wire form.
fn greeting_to_proto(g: Greeting) -> pb::Greeting {
    pb::Greeting {
        id: g.id.0.to_string(),
        name: g.name,
        body: g.body,
        created: g.created.to_rfc3339(),
        ..Default::default()
    }
}

/// Convert a note view (with the viewer's server-computed flags) into proto.
fn note_to_proto(n: NoteView) -> pb::Note {
    pb::Note {
        id: n.id.0.to_string(),
        title: n.title,
        body: n.body,
        created: n.created.to_rfc3339(),
        viewer_can_edit: n.viewer_can_edit,
        viewer_can_share: n.viewer_can_share,
        ..Default::default()
    }
}

/// Parse a `(principal_kind, principal_id)` pair from a `ShareNote` request.
fn parse_principal(kind: &str, id: &str) -> Result<Principal, ConnectError> {
    let parse_uuid =
        || Uuid::parse_str(id).map_err(|_| ConnectError::invalid_argument("invalid principal_id"));
    match kind {
        "user" => Ok(Principal::User(UserId(parse_uuid()?))),
        "group" => Ok(Principal::Group(GroupId(parse_uuid()?))),
        "public" => Ok(Principal::Public),
        _ => Err(ConnectError::invalid_argument(
            "principal_kind must be user, group, or public",
        )),
    }
}

/// Per-request state for the hello plugin: its repositories, typed on the
/// permission witness `P`. `#[derive(PluginCtx)]` generates the extractor for
/// `HelloCtx<P>`.
#[derive(PluginCtx)]
pub struct HelloState<P = ()> {
    #[repo]
    pub greetings: HelloRepo<P>,
    #[repo]
    pub notes: NoteRepo<P>,
}

/// The hello plugin's request context: state + caller + resources, proven to
/// hold the permissions in `P`.
pub type HelloCtx<P = ()> = PluginContext<HelloState<P>, P>;

/// `GET /h/hello/greetings` — list greetings. Requires `hello:read`, enforced by
/// extracting `HelloCtx<permissions!(HelloRead)>`.
async fn list_greetings(
    ctx: HelloCtx<junius_sdk::permissions!(HelloRead)>,
) -> Result<Json<Vec<Greeting>>, ApiError> {
    Ok(Json(ctx.state.greetings.list().await?))
}

pub struct HelloPlugin;

impl HelloPlugin {
    #[must_use]
    pub fn new() -> Self {
        Self
    }
}

impl Default for HelloPlugin {
    fn default() -> Self {
        Self::new()
    }
}

/// Connect-RPC implementation of `hello.v1.HelloService`. `Greet` is permission-
/// free; the CRUD methods build a typed `HelloCtx<P>` from the request context
/// (`from_rpc`), which re-checks the witness and yields the permission-gated
/// repository. The host's RPC guard also enforces each method's
/// `(platform.v1.requires)` before the handler runs.
struct HelloRpc;

impl HelloService for HelloRpc {
    async fn greet(
        &self,
        _ctx: RequestContext,
        request: OwnedGreetRequestView,
    ) -> ServiceResult<impl Encodable<GreetResponse>> {
        let name = if request.name.is_empty() {
            "world"
        } else {
            request.name
        };
        Ok(Response::new(GreetResponse {
            message: format!("Hello, {name}!"),
            ..Default::default()
        }))
    }

    async fn list_greetings(
        &self,
        ctx: RequestContext,
        _request: OwnedListGreetingsRequestView,
    ) -> ServiceResult<impl Encodable<pb::ListGreetingsResponse>> {
        let hctx = HelloCtx::<junius_sdk::permissions!(HelloRead)>::from_rpc(&ctx)?;
        let greetings = hctx.state.greetings.list().await?;
        Ok(Response::new(pb::ListGreetingsResponse {
            greetings: greetings.into_iter().map(greeting_to_proto).collect(),
            ..Default::default()
        }))
    }

    async fn create_greeting(
        &self,
        ctx: RequestContext,
        request: OwnedCreateGreetingRequestView,
    ) -> ServiceResult<impl Encodable<pb::CreateGreetingResponse>> {
        let hctx = HelloCtx::<junius_sdk::permissions!(HelloRead & HelloWrite)>::from_rpc(&ctx)?;
        let created = hctx
            .state
            .greetings
            .create(NewGreeting {
                name: request.name.to_string(),
                body: request.body.to_string(),
            })
            .await?;
        // Enqueue the follow-up email (best-effort: a missing/unconfigured job
        // backend must not fail the create).
        let job = SendGreeting {
            greeting_id: created.id.0.to_string(),
            name: created.name.clone(),
            body: created.body.clone(),
            recipient_email: "recipient@local".to_string(),
            // Best-effort: in a full integration this would look up the
            // recipient user's `platform.user.locale`. The test fixture
            // has no such user yet, so we fall back to the deployment default.
            recipient_locale: hctx
                .resources
                .auth
                .current_user()
                .and_then(|u| u.locale.clone()),
        };
        if let Err(e) = hctx.resources.jobs.enqueue(job).await {
            tracing::warn!(error = %e, "failed to enqueue hello.send_greeting");
        }
        Ok(Response::new(pb::CreateGreetingResponse {
            greeting: Some(greeting_to_proto(created)).into(),
            ..Default::default()
        }))
    }
}

/// Connect-RPC implementation of `hello.v1.NoteService` — the M08 per-resource
/// access demo. Reads are filtered by `platform.user_can_access` in the repo;
/// `CreateNote` records ownership; `ShareNote` delegates to the host's owner-
/// checked `authz.share`.
struct NoteRpc;

impl NoteService for NoteRpc {
    async fn list_notes(
        &self,
        ctx: RequestContext,
        _request: OwnedListNotesRequestView,
    ) -> ServiceResult<impl Encodable<pb::ListNotesResponse>> {
        let hctx = HelloCtx::<junius_sdk::permissions!(HelloRead)>::from_rpc(&ctx)?;
        let notes = hctx.state.notes.list().await?;
        Ok(Response::new(pb::ListNotesResponse {
            notes: notes.into_iter().map(note_to_proto).collect(),
            ..Default::default()
        }))
    }

    async fn get_note(
        &self,
        ctx: RequestContext,
        request: OwnedGetNoteRequestView,
    ) -> ServiceResult<impl Encodable<pb::GetNoteResponse>> {
        let id = Uuid::parse_str(request.id)
            .map_err(|_| ConnectError::invalid_argument("invalid note id"))?;
        let hctx = HelloCtx::<junius_sdk::permissions!(HelloRead)>::from_rpc(&ctx)?;
        let note = hctx.state.notes.get(NoteId(id)).await?;
        Ok(Response::new(pb::GetNoteResponse {
            note: Some(note_to_proto(note)).into(),
            ..Default::default()
        }))
    }

    async fn create_note(
        &self,
        ctx: RequestContext,
        request: OwnedCreateNoteRequestView,
    ) -> ServiceResult<impl Encodable<pb::CreateNoteResponse>> {
        let hctx = HelloCtx::<junius_sdk::permissions!(HelloRead & HelloWrite)>::from_rpc(&ctx)?;
        let note = hctx
            .state
            .notes
            .create(
                NewNote {
                    title: request.title.to_string(),
                    body: request.body.to_string(),
                },
                &hctx.resources.authz,
            )
            .await?;
        Ok(Response::new(pb::CreateNoteResponse {
            note: Some(note_to_proto(note)).into(),
            ..Default::default()
        }))
    }

    async fn share_note(
        &self,
        ctx: RequestContext,
        request: OwnedShareNoteRequestView,
    ) -> ServiceResult<impl Encodable<pb::ShareNoteResponse>> {
        let note_id = Uuid::parse_str(request.id)
            .map_err(|_| ConnectError::invalid_argument("invalid note id"))?;
        let principal = parse_principal(request.principal_kind, request.principal_id)?;
        let hctx = HelloCtx::<junius_sdk::permissions!(HelloRead)>::from_rpc(&ctx)?;
        let share = hctx
            .resources
            .authz
            .share("hello:note", note_id, principal, request.permission, None)
            .await?;
        Ok(Response::new(pb::ShareNoteResponse {
            share_id: share.id.to_string(),
            ..Default::default()
        }))
    }
}

#[async_trait]
impl Plugin for HelloPlugin {
    fn metadata(&self) -> &'static PluginMetadata {
        &METADATA
    }

    fn routes(&self) -> Router {
        Router::new()
            .route("/ping", get(|| async { "pong" }))
            .route("/greetings", get(list_greetings))
    }

    fn register_rpc(&self, router: connectrpc::Router) -> connectrpc::Router {
        let router = Arc::new(HelloRpc).register(router);
        Arc::new(NoteRpc).register(router)
    }

    fn jobs(&self) -> Vec<JobHandler> {
        vec![JobHandler::new::<SendGreeting, _, _>(send_greeting_handler)]
    }

    fn register_i18n(&self, builder: &mut junius_sdk::LocalizerBuilder) {
        catalog::register(builder);
    }
}
